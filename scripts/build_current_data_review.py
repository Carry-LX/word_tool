def read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def parse_recipe_blocks(text: str) -> list[dict[str, Any]]:
    """Small YAML-subset reader for the recipe file generated by our script."""
    blocks = re.split(r"\n  -\n", text)
    recipe_blocks = [block for block in blocks[1:] if "artifact_id:" in block]
    recipes = []
    for block in recipe_blocks:
        item: dict[str, Any] = {}
        sources = []
        current_source: dict[str, Any] | None = None
        for raw_line in block.splitlines():
            line = raw_line.rstrip()
            stripped = line.strip()
            if stripped.startswith("artifact_id:"):
                item["artifact_id"] = stripped.split(":", 1)[1].strip().strip('"')
            elif stripped.startswith("artifact_type:"):
                item["artifact_type"] = stripped.split(":", 1)[1].strip().strip('"')
            elif stripped.startswith("section:"):
                item["section"] = stripped.split(":", 1)[1].strip().strip('"')
            elif stripped.startswith("reference_caption:"):
                item["reference_caption"] = stripped.split(":", 1)[1].strip().strip('"')
            elif stripped.startswith("readiness:"):
                item["readiness"] = stripped.split(":", 1)[1].strip().strip('"')
            elif stripped.startswith("priority:"):
                item["priority"] = stripped.split(":", 1)[1].strip().strip('"')
            elif stripped.startswith("source_id:"):
                current_source = {"source_id": stripped.split(":", 1)[1].strip().strip('"')}
                sources.append(current_source)
            elif current_source is not None and stripped.startswith("file:"):
                current_source["file"] = stripped.split(":", 1)[1].strip().strip('"')
            elif current_source is not None and stripped.startswith("sheet:"):
                current_source["sheet"] = stripped.split(":", 1)[1].strip().strip('"')
            elif current_source is not None and stripped.startswith("role:"):
                current_source["role"] = stripped.split(":", 1)[1].strip().strip('"')
        item["data_sources"] = sources
        recipes.append(item)
    return recipes


def write_text(path: Path, content: str) -> None:
    path.write_text(content, encoding="utf-8", newline="\n")


def build_matrix_csv(recipes: list[dict[str, Any]]) -> str:
    lines = [
        "artifact_id,priority,readiness,artifact_type,section,source_ids,files,reference_caption"
    ]
    for item in recipes:
        source_ids = "; ".join(sorted({source.get("source_id", "") for source in item["data_sources"]}))
        files = "; ".join(sorted({source.get("file", "") for source in item["data_sources"]}))
        row = [
            item.get("artifact_id", ""),
            item.get("priority", ""),
            item.get("readiness", ""),
            item.get("artifact_type", ""),
            item.get("section", ""),
            source_ids,
            files,
            item.get("reference_caption", ""),
        ]
        escaped = []
        for value in row:
            text = str(value).replace('"', '""')
            escaped.append(f'"{text}"')
        lines.append(",".join(escaped))
    return "\n".join(lines) + "\n"


def build_logic_review(
    catalog: dict[str, Any],
    registry: dict[str, Any],
    validation: dict[str, Any],
    recipes: list[dict[str, Any]],
) -> str:
    readiness = Counter(item.get("readiness") for item in recipes)
    priority = Counter(item.get("priority") for item in recipes)
    source_usage: Counter[str] = Counter()
    role_usage: Counter[str] = Counter()
    artifacts_by_layer: dict[str, list[str]] = defaultdict(list)

    layer_map = {
        "ready_after_fact_ranking": "fact_ranking",
        "ready_after_fact_ranking_indicator": "fact_ranking_indicator",
        "ready_after_weight_cleaning": "fact_indicator_weight",
        "partial_needs_indicator_grouping": "fact_indicator_weight + indicator_group_mapping",
        "partial_proxy_only": "proxy_metrics",
        "ready_with_caveat": "fact_domestic_evaluation",
        "data_gap": "missing_external_data",
    }

    for item in recipes:
        artifacts_by_layer[layer_map.get(item.get("readiness"), "other")].append(item.get("artifact_id", ""))
        for source in item["data_sources"]:
            source_usage[source.get("source_id", "")] += 1
            role_usage[source.get("role", "")] += 1

    core_sources = [entry for entry in registry["excel_sources"] if entry["tier"] == "core"]
    current_sources = [entry for entry in registry["excel_sources"] if entry["tier"] == "current"]

    lines = [
        "# 当前数据复核与整体逻辑",
        "",
        "## 复核结论",
        "",
        "当前数据部分已经达到“可进入结构化入库”的清晰度：源文件已注册、参考报告图表已索引、每个主要图表已有字段级 recipe，且 recipe 引用的文件、sheet、字段均通过自动核验。",
        "",
        "但还没有完成真正的数据入库和清洗。因此下一阶段的重点不是继续加文档，而是把统一数据模型落成 `processed/` 中的事实表和维表。",
        "",
        "## 机器核验结果",
        "",
        f"- Excel 文件数：{catalog['excel_count']}",
        f"- Excel sheet 数：{sum(len(workbook.get('sheets', [])) for workbook in catalog['workbooks'])}",
        f"- 注册 Excel 源：{len(registry['excel_sources'])}",
        f"- 未注册 Excel：{len(registry['unregistered_excel_files'])}",
        f"- Artifact recipe 数：{validation['recipe_count']}",
        f"- 缺失文件：{validation['missing_file_count']}",
        f"- 缺失 sheet：{validation['missing_sheet_count']}",
        f"- 缺失字段：{validation['missing_field_count']}",
        "",
        "## 核心数据源",
        "",
        "### core",
        "",
    ]
    for entry in core_sources:
        lines.append(f"- `{entry['file']}`：{entry['role']}；{entry['purpose']}")

    lines.extend(["", "### current", ""])
    for entry in current_sources:
        lines.append(f"- `{entry['file']}`：{entry['role']}；{entry['purpose']}")

    lines.extend(["", "## Recipe 状态分布", ""])
    for key, value in readiness.items():
        lines.append(f"- `{key}`：{value}")

    lines.extend(["", "## 优先级分布", ""])
    for key in ["P1", "P2", "P3", "P4"]:
        lines.append(f"- `{key}`：{priority.get(key, 0)}")

    lines.extend(["", "## 数据层到图表的依赖", ""])
    for layer, artifact_ids in artifacts_by_layer.items():
        lines.append(f"### {layer}")
        lines.append("")
        for artifact_id in artifact_ids:
            lines.append(f"- `{artifact_id}`")
        lines.append("")

    lines.extend(["## 最常被使用的数据源", ""])
    for source_id, count in source_usage.most_common(12):
        lines.append(f"- `{source_id}`：{count} 个 artifact")

    lines.extend(["", "## 当前仍需人工确认的口径", ""])
    lines.extend(
        [
            "1. 对标高校范围：默认建议先做 `mainland_top200_by_ranking`，再支持双一流、第五轮同档、用户指定名单。",
            "2. 目标学科输入方式：建议支持“一级学科名称”优先，其次支持“学院名称”，通过 `dim_subject` 解析到四大榜单学科。",
            "3. 排名年份口径：报告中必须同时记录发布年度和排名年度，图题按实际数据口径写。",
            "4. 论文实力：当前只能做榜单代理指标，除非补 WOS/Scopus 论文数据。",
            "5. 研究前沿：当前是明确缺口，不能生成强结论。",
        ]
    )

    return "\n".join(lines) + "\n"


