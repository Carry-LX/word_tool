def main() -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    catalog = read_json(STAGE1_DIR / "data_catalog.json")
    registry = read_json(GOVERNANCE_DIR / "source_registry.json")
    validation = read_json(RECIPES_DIR / "recipe_validation.json")
    recipe_text = (RECIPES_DIR / "artifact_data_recipes.yaml").read_text(encoding="utf-8")
    recipes = parse_recipe_blocks(recipe_text)

    write_text(OUTPUT_DIR / "artifact_source_matrix.csv", build_matrix_csv(recipes))
    write_text(OUTPUT_DIR / "current_data_logic_review.md", build_logic_review(catalog, registry, validation, recipes))
    write_text(OUTPUT_DIR / "next_phase_plan.md", build_next_phase_plan())

    print((OUTPUT_DIR / "current_data_logic_review.md").read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
